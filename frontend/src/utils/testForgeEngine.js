/**
 * Core test synthesis and analysis engine for TestForge AI.
 * Parses raw FastAPI Python code, extracts route signatures, detects potential
 * unhandled bugs/defects, and generates realistic pytest test suites and agent execution logs.
 */

export function analyzeFastApiRoutes(code) {
  if (!code || typeof code !== 'string') {
    return {
      routes: [],
      hasDefect: false,
      defectInfo: null,
      detectedFramework: 'FastAPI',
      totalLines: 0
    };
  }

  const lines = code.split('\n');
  const routes = [];

  // Regex to match FastAPI decorators: @app.get('/path'), @router.post("/items/{id}") etc.
  const routeRegex = /@(app|router)\.(get|post|put|delete|patch|options)\s*\(\s*["']([^"']+)["']/g;
  let match;

  while ((match = routeRegex.exec(code)) !== null) {
    const method = match[2].toUpperCase();
    const path = match[3];
    routes.push({
      method,
      path,
      decorator: match[0]
    });
  }

  // Detect bug patterns or triggers
  const lowerCode = code.toLowerCase();
  let hasDefect = false;
  let defectInfo = null;

  if (
    lowerCode.includes('defect') ||
    lowerCode.includes('zerodivisionerror') ||
    lowerCode.includes('division by zero') ||
    /(\/|\%)\s*0\b/.test(code) ||
    (lowerCode.includes('payment') && lowerCode.includes('tax_rate') && !lowerCode.includes('except zerodivisionerror'))
  ) {
    hasDefect = true;
    defectInfo = {
      type: 'ZeroDivisionError / 500 Unhandled Math Exception',
      file: 'app.py',
      location: 'calculate_tax() / line in @app.post("/api/v1/checkout")',
      message: 'Float division by zero when discount_factor equals 1.0. Endpoint crashes with unhandled 500 Internal Server Error instead of 400 Bad Request.',
      recommendation: 'Add guard check `if discount_factor >= 1.0: raise HTTPException(status_code=400, detail="Invalid discount factor")`'
    };
  } else if (
    lowerCode.includes('keyerror') ||
    (lowerCode.includes('payload[') && !lowerCode.includes('get(') && !lowerCode.includes('pydantic'))
  ) {
    hasDefect = true;
    defectInfo = {
      type: 'KeyError / Missing Request Body Validation',
      file: 'app.py',
      location: 'Route body handler',
      message: 'Direct dictionary key access `payload["user_id"]` causes unhandled KeyError on malformed requests.',
      recommendation: 'Use a Pydantic BaseModel or `payload.get("user_id")` with standard HTTP 422 Unprocessable Entity.'
    };
  } else if (lowerCode.includes('simulate_defect: true') || lowerCode.includes('# bug:')) {
    hasDefect = true;
    defectInfo = {
      type: 'Unhandled Edge-Case Exception',
      file: 'app.py',
      location: 'Route handler exception boundary',
      message: 'Autonomous fuzzer encountered unhandled exception during boundary null mutation test.',
      recommendation: 'Implement explicit error response schema and input bounds validation.'
    };
  }

  return {
    routes,
    hasDefect,
    defectInfo,
    detectedFramework: routes.length > 0 ? 'FastAPI (Python)' : 'Python ASGI Route',
    totalLines: lines.length
  };
}

export function synthesizePytestSuite(code, analysis) {
  const routes = analysis.routes && analysis.routes.length > 0 ? analysis.routes : [
    { method: 'GET', path: '/health' },
    { method: 'POST', path: '/items' }
  ];

  const hasDefect = analysis.hasDefect;

  const testCases = routes.map((route, idx) => {
    const funcName = `test_${route.method.toLowerCase()}_${route.path.replace(/[^a-zA-Z0-9]/g, '_').replace(/_+/g, '_').replace(/^_|_$/g, '') || 'endpoint'}_success`;
    const isPostOrPut = ['POST', 'PUT', 'PATCH'].includes(route.method);

    let testBody = '';
    if (isPostOrPut) {
      testBody = `    # Arrange: Synthetic boundary payload generated by TestForge AI
    payload = {
        "id": "tf_${1000 + idx}",
        "name": "Autonomous Test Item ${idx + 1}",
        "active": True,
        "metadata": {"source": "testforge-sandbox"}
    }
    
    # Act: Perform HTTP call against isolated TestClient
    response = client.${route.method.toLowerCase()}("${route.path}", json=payload)
    
    # Assert: Validate response contract and payload persistence
    assert response.status_code in [200, 201, 202], f"Expected 20x, got {response.status_code}: {response.text}"
    assert response.headers["content-type"].startswith("application/json")`;
    } else {
      testBody = `    # Act: Query target route with parameterized edge fixtures
    response = client.${route.method.toLowerCase()}("${route.path}")
    
    # Assert: Check health contract & response schema
    assert response.status_code == 200, f"Expected 200 OK, got {response.status_code}"
    assert response.json() is not None`;
    }

    return `def ${funcName}(client: TestClient):
    """
    [TestForge Synthetic Spec #${idx + 1}]
    Validates happy path contract for ${route.method} ${route.path}.
    Self-healed from fixture mismatch: converted client session to isolated context.
    """
${testBody}
`;
  }).join('\n');

  // Add boundary / negative test case
  const negativeTestCase = `def test_boundary_validation_error(client: TestClient):
    """
    [TestForge Boundary Fuzzing Spec]
    Verifies that malformed payloads trigger HTTP 422 Unprocessable Entity
    without causing unhandled server-side 500 exceptions.
    """
    malformed_payload = {"invalid_key": None, "overflow_int": 999999999999}
    response = client.post("${routes[0]?.path || '/api'}", json=malformed_payload)
    
    # System must fail safely with standard 4xx rather than unhandled 500
    assert response.status_code in [400, 422, 404, 405], f"Unexpected code: {response.status_code}"
`;

  const defectReproTest = hasDefect ? `
def test_reproduce_source_defect_edge_case(client: TestClient):
    """
    [DEFECT REPRODUCTION TEST - FAILED IN PRE-HEALING RUN]
    This test reproduces the identified defect in source code:
    ${analysis.defectInfo?.type || 'Unhandled Edge Case'}
    ${analysis.defectInfo?.message || ''}
    """
    # Trigger boundary case that exposed unhandled 500
    edge_payload = {"amount": 500.0, "discount_factor": 1.0}
    response = client.post("${routes[0]?.path || '/checkout'}", json=edge_payload)
    
    # The server currently crashes with 500!
    # Expected behavior: Safe 400 Bad Request or handled calculation
    assert response.status_code != 500, "CRITICAL DEFECT: Route crashed with 500 Internal Server Error!"
` : '';

  return `"""
================================================================================
TestForge AI - Autonomous Test Suite: test_app.py
Target Framework: FastAPI / ASGI
Generated: Autonomous QA Agent v2.4 (Self-Healing Active)
================================================================================
"""

import pytest
from fastapi.testclient import TestClient

# Import app instance under test (healed import path)
try:
    from app import app
except ImportError:
    from main import app  # type: ignore

@pytest.fixture(scope="module")
def client():
    """
    Isolated test fixture with automatic ASGI lifespan context.
    Self-healed: prevents database connection pool exhaustion across suites.
    """
    with TestClient(app) as test_client:
        yield test_client

# ==============================================================================
# Synthesized Test Cases (${routes.length} Generated Routes)
# ==============================================================================

${testCases}
${negativeTestCase}${defectReproTest}
# ==============================================================================
# End of Autonomous Test Suite - TestForge AI
# ==============================================================================
`;
}

